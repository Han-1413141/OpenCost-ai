type BroadDomain =
  | 'software'
  | 'writing'
  | 'research'
  | 'data'
  | 'design'
  | 'office'
  | 'operations'
  | 'education'
  | 'other';
export type WorkDomainDefinition = {
  id: string;
  label: string;
  parentDomains: readonly BroadDomain[];
  units: readonly WorkUnit[];
  acceptance: readonly string[];
  activities: readonly { id: string; label: string }[];
};
function domain(
  id: string,
  label: string,
  parentDomains: BroadDomain[],
  units: WorkUnit[],
  acceptance: string[],
  activities: Record<string, string>,
): WorkDomainDefinition {
  return {
    id,
    label,
    parentDomains,
    units,
    acceptance,
    activities: Object.entries(activities).map(([code, title]) => ({
      id: `${id}.${code}`,
      label: title,
    })),
  };
}

